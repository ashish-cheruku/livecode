class QueryResponse(BaseModel):
    """
    Full response returned by POST /api/query.

    The frontend uses:
      - `answer`        → rendered in the chat bubble
      - `pipeline`      → drives the colour-coded PipelineBadge component
      - `artifacts`     → rendered in the collapsible ArtifactsPanel component
      - `processing_time_ms` → optional display in the UI footer
    """

    answer: str = Field(
        ...,
        description="Natural language answer synthesised by the LLM.",
        examples=[
            "Department D_402's total revenue for fiscal year 2025 was $98.5M "
            "($47.3M in Q3 and $51.2M in Q4)."
        ],
    )
    pipeline: PipelineType = Field(
        ...,
        description="The pipeline that was used to generate this answer.",
        examples=[PipelineType.SQL],
    )
    artifacts: Artifacts = Field(
        default_factory=Artifacts,
        description=(
            "Intermediate pipeline artifacts (generated SQL, retrieved chunks, etc.) "
            "for transparency and debugging. Fields are None when not applicable "
            "to the pipeline used."
        ),
    )
    processing_time_ms: Optional[float] = Field(
        default=None,
        description="Total server-side processing time in milliseconds.",
        examples=[1243.7],
    )
    error: Optional[str] = Field(
        default=None,
        description=(
            "Error message if the pipeline encountered a recoverable error "
            "but still returned a partial answer. None on full success."
        ),
    )

    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "answer": (
                        "Department D_402's total revenue for fiscal year 2025 was $98.5M "
                        "($47.3M in Q3 and $51.2M in Q4)."
                    ),
                    "pipeline": "SQL",
                    "artifacts": {
                        "sql_query": (
                            "SELECT fq_lbl, rev_raw_m FROM erp_fin_qtr_export "
                            "WHERE dept_id_ref = 'D_402' AND fy_yr = 2025"
                        ),
                        "sql_results": [
                            {"fq_lbl": "Q3", "rev_raw_m": 47.3},
                            {"fq_lbl": "Q4", "rev_raw_m": 51.2},
                        ],
                        "sql_row_count": 2,
                        "retrieved_chunks": None,
                        "chunk_scores": None,
                        "chunk_metadata": None,
                    },
                    "processing_time_ms": 1243.7,
                    "error": None,
                }
            ]
        }
    }


class HealthResponse(BaseModel):
    """
    Response returned by GET /api/health.

    Provides a top-level status and per-component readiness flags so that
    infrastructure monitoring tools can distinguish between a fully healthy
    service and one that is partially degraded.
    """

    status: str = Field(
        ...,
        description="Overall service status. 'ok' when all components are healthy.",
        examples=["ok", "degraded"],
    )
    components: dict[str, str] = Field(
        ...,
        description=(
            "Per-component status map. Keys are component names; "
            "values are 'ok', 'degraded', or 'unavailable'."
        ),
        examples=[
            {
                "sqlite": "ok",
                "chromadb": "ok",
                "openai": "ok",
            }
        ],
    )
    version: str = Field(
        default="1.0.0",
        description="API version string.",
        examples=["1.0.0"],
    )

    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "status": "ok",
                    "components": {
                        "sqlite": "ok",
                        "chromadb": "ok",
                        "openai": "ok",
                    },
                    "version": "1.0.0",
                }
            ]
        }
    }

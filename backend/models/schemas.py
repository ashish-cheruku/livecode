"""
Pydantic request/response models for the Enterprise Hybrid Agent API.

These models define the contract between the FastAPI backend and the
React frontend.  Every field is explicitly typed and documented so that
FastAPI's auto-generated OpenAPI schema is self-explanatory.
"""

from __future__ import annotations

from enum import Enum
from typing import Any, Optional

from pydantic import BaseModel, Field, field_validator, model_validator


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------


class PipelineType(str, Enum):
    """
    Which retrieval pipeline was used to answer the query.

    Inheriting from `str` ensures the value serialises as a plain JSON string
    ("SQL", "VECTOR", "HYBRID") rather than an integer ordinal, so the
    frontend can consume it directly without any mapping layer.
    """

    SQL = "SQL"
    VECTOR = "VECTOR"
    HYBRID = "HYBRID"


# ---------------------------------------------------------------------------
# Request models
# ---------------------------------------------------------------------------


class QueryRequest(BaseModel):
    """
    Payload sent by the frontend when the user submits a question.
    """

    question: str = Field(
        ...,
        min_length=3,
        max_length=2000,
        description=(
            "Natural language question to be answered by the agent. "
            "Must be between 3 and 2000 characters."
        ),
        examples=["What was the total revenue for department D_402 in fiscal year 2025?"],
    )

    @field_validator("question", mode="before")
    @classmethod
    def strip_and_validate_question(cls, v: Any) -> str:
        """Strip surrounding whitespace and reject blank strings."""
        if not isinstance(v, str):
            raise ValueError("question must be a string")
        stripped = v.strip()
        if not stripped:
            raise ValueError("question must not be blank or whitespace-only")
        return stripped

    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "question": (
                        "What was the total revenue for department D_402 "
                        "in fiscal year 2025?"
                    )
                },
                {"question": "What is Project Phoenix and what are its expected outcomes?"},
                {
                    "question": (
                        "Why did department D_402's EBITDA margin improve "
                        "from Q3 to Q4 2025, and what strategic initiative drove it?"
                    )
                },
            ]
        }
    }



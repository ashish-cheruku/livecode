class SQLArtifacts(BaseModel):
    """
    Artifacts produced by the Text-to-SQL pipeline.
    All fields are optional because this model is reused inside the combined
    Artifacts wrapper where SQL fields may be absent (e.g. pure Vector query).
    """

    sql_query: Optional[str] = Field(
        default=None,
        description="The SQL SELECT statement generated by the LLM and executed against SQLite.",
        examples=["SELECT SUM(rev_raw_m) FROM erp_fin_qtr_export WHERE dept_id_ref = 'D_402' AND fy_yr = 2025"],
    )
    sql_results: Optional[list[dict[str, Any]]] = Field(
        default=None,
        description=(
            "Raw rows returned by the SQL query, serialised as a list of dicts "
            "(column name → value). Empty list if the query returned no rows."
        ),
        examples=[[{"SUM(rev_raw_m)": 98.5}]],
    )
    sql_row_count: Optional[int] = Field(
        default=None,
        description="Number of rows returned by the SQL query.",
        examples=[1],
    )


class VectorArtifacts(BaseModel):
    """
    Artifacts produced by the Vector Search pipeline.
    """

    retrieved_chunks: Optional[list[str]] = Field(
        default=None,
        description=(
            "Text content of the top-k document chunks retrieved from ChromaDB, "
            "ordered by relevance (most relevant first)."
        ),
    )
    chunk_scores: Optional[list[float]] = Field(
        default=None,
        description=(
            "Cosine distance scores for each retrieved chunk (lower = more similar). "
            "Parallel array to retrieved_chunks."
        ),
        examples=[[0.1823, 0.2541, 0.3102]],
    )
    chunk_metadata: Optional[list[dict[str, Any]]] = Field(
        default=None,
        description=(
            "Metadata dicts for each retrieved chunk (source document, section, date, etc.). "
            "Parallel array to retrieved_chunks."
        ),
    )

    @model_validator(mode="after")
    def validate_parallel_arrays(self) -> "VectorArtifacts":
        """
        Ensure retrieved_chunks, chunk_scores, and chunk_metadata have the
        same length when all three are provided.
        """
        arrays = {
            "retrieved_chunks": self.retrieved_chunks,
            "chunk_scores": self.chunk_scores,
            "chunk_metadata": self.chunk_metadata,
        }
        populated = {k: v for k, v in arrays.items() if v is not None}
        if len(populated) > 1:
            lengths = {k: len(v) for k, v in populated.items()}
            if len(set(lengths.values())) > 1:
                raise ValueError(
                    f"retrieved_chunks, chunk_scores, and chunk_metadata must have "
                    f"the same length. Got: {lengths}"
                )
        return self


class Artifacts(BaseModel):
    """
    Combined artifacts container returned in every QueryResponse.

    SQL fields are populated for SQL and HYBRID pipelines.
    Vector fields are populated for VECTOR and HYBRID pipelines.
    All fields are optional — the frontend checks for None before rendering.
    """

    # SQL pipeline artifacts
    sql_query: Optional[str] = Field(
        default=None,
        description="The SQL SELECT statement generated by the LLM.",
    )
    sql_results: Optional[list[dict[str, Any]]] = Field(
        default=None,
        description="Raw rows returned by the SQL query as a list of dicts.",
    )
    sql_row_count: Optional[int] = Field(
        default=None,
        description="Number of rows returned by the SQL query.",
    )

    # Vector pipeline artifacts
    retrieved_chunks: Optional[list[str]] = Field(
        default=None,
        description="Text of the top-k document chunks retrieved from ChromaDB.",
    )
    chunk_scores: Optional[list[float]] = Field(
        default=None,
        description="Cosine distance scores for each retrieved chunk (lower = more similar).",
    )
    chunk_metadata: Optional[list[dict[str, Any]]] = Field(
        default=None,
        description="Metadata dicts for each retrieved chunk.",
    )

    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "sql_query": (
                        "SELECT fy_yr, fq_lbl, ebitda_adj_pct "
                        "FROM erp_fin_qtr_export "
                        "WHERE dept_id_ref = 'D_402' "
                        "ORDER BY fy_yr, fq_lbl"
                    ),
                    "sql_results": [
                        {"fy_yr": 2024, "fq_lbl": "Q3", "ebitda_adj_pct": 0.229},
                        {"fy_yr": 2025, "fq_lbl": "Q4", "ebitda_adj_pct": 0.285},
                    ],
                    "sql_row_count": 2,
                    "retrieved_chunks": None,
                    "chunk_scores": None,
                    "chunk_metadata": None,
                }
            ]
        }
    }


